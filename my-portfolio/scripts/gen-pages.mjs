// Generates an HTML entry (<slug>/index.html) for every SEO landing page in src/data/landings.js,
// and refreshes their block in public/sitemap.xml. Runs before `vite` and `vite build`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { landings, landingUrl } from '../src/data/landings.js'

const root = fileURLToPath(new URL('..', import.meta.url))
const today = new Date().toISOString().slice(0, 10)

const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

const assets = {
  qr: { icon: 'qr', touch: 'apple-touch-qr.png', og: 'og-qr.jpg' },
  resizer: { icon: 'resizer', touch: 'apple-touch-resizer.png', og: 'og-image.jpg' },
  file: { icon: 'pdf', touch: 'apple-touch-icon.png', og: 'og-image.jpg', svgOnly: true },
  audio: { icon: 'audio', touch: 'apple-touch-icon.png', og: 'og-image.jpg', svgOnly: true },
}

function html(p) {
  const url = landingUrl(p)
  const a = assets[p.tool]
  const og = `https://samarthdalela.xyz/${a.og}`
  return `<!doctype html>
<!-- Generated by scripts/gen-pages.mjs from src/data/landings.js — edit that file, not this one. -->
<html lang="en-IN">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />

    <!-- Primary SEO -->
    <title>${esc(p.title)}</title>
    <meta name="description" content="${esc(p.description)}" />
    <meta name="keywords" content="${esc(p.keywords)}" />
    <meta name="author" content="Samarth Dalela" />
    <meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1" />
    <link rel="canonical" href="${url}" />
    <meta name="theme-color" content="#07080f" />

${a.svgOnly ? '' : `    <link rel="icon" type="image/png" sizes="48x48" href="/favicon-${a.icon}-48.png" />\n`}    <link rel="icon" type="image/svg+xml" href="/favicon-${a.icon}.svg" />
    <link rel="apple-touch-icon" href="/${a.touch}" />
    <link rel="manifest" href="/site.webmanifest" />

    <!-- Open Graph -->
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Samarth Dalela" />
    <meta property="og:url" content="${url}" />
    <meta property="og:title" content="${esc(p.title)}" />
    <meta property="og:description" content="${esc(p.description)}" />
    <meta property="og:image" content="${og}" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="Free ${esc(p.name)}" />
    <meta property="og:locale" content="en_IN" />

    <!-- Twitter / X -->
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${esc(p.title)}" />
    <meta name="twitter:description" content="${esc(p.description)}" />
    <meta name="twitter:image" content="${og}" />

    <!-- Structured data (WebApplication, HowTo, FAQPage, Breadcrumbs) is rendered into the page body -->

    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Space+Grotesk:wght@500;600;700&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet" />
    <script>
      try {
        var t = localStorage.getItem('theme')
        if (!t) t = matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark'
        document.documentElement.dataset.theme = t
      } catch (e) {}
    </script>
  </head>
  <body>
    <div id="root" data-page="${p.slug}"><!--app-html--></div>
    <noscript><style>.reveal { opacity: 1; transform: none; }</style></noscript>
    <script type="module" src="/src/landing-main.jsx"></script>
  </body>
</html>
`
}

for (const p of landings) {
  mkdirSync(`${root}${p.slug}`, { recursive: true })
  writeFileSync(`${root}${p.slug}/index.html`, html(p))
}

// Replace the landing-pages block in the sitemap; the rest of the file is edited by hand.
const START = '  <!-- landing pages: generated by scripts/gen-pages.mjs -->'
const END = '  <!-- /landing pages -->'
const sitemapPath = `${root}public/sitemap.xml`
const sitemap = readFileSync(sitemapPath, 'utf8')
const prev = sitemap.includes(START) ? sitemap.slice(sitemap.indexOf(START), sitemap.indexOf(END) + END.length) : ''
// Keep each page's old lastmod unless its entry is new, so the sitemap only changes when pages do.
const lastmod = (url) => prev.match(new RegExp(`<loc>${url}</loc>\\s*<lastmod>([^<]+)`))?.[1] || today
const block = [
  START,
  ...landings.map(
    (p) => `  <url>
    <loc>${landingUrl(p)}</loc>
    <lastmod>${lastmod(landingUrl(p))}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>`,
  ),
  END,
].join('\n')
writeFileSync(sitemapPath, prev ? sitemap.replace(prev, block) : sitemap.replace('</urlset>', `${block}\n</urlset>`))

console.log(`Generated ${landings.length} landing pages`)
