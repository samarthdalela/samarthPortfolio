import react from '@vitejs/plugin-react'
import { defineConfig, loadEnv } from 'vite'
import { landings } from './src/data/landings.js'

// Serves the Vercel functions in api/ during `npm run dev`, so the contact form works locally.
// Env vars are read server-side only; nothing without a VITE_ prefix reaches the browser.
function devApi(mode) {
  return {
    name: 'dev-api',
    configureServer(server) {
      Object.assign(process.env, loadEnv(mode, process.cwd(), ''))
      for (const route of ['contact']) {
        server.middlewares.use(`/api/${route}`, async (req, res) => {
          const { default: handler } = await server.ssrLoadModule(`/api/${route}.js`)
          await handler(req, res)
        })
      }
    },
  }
}

// https://vite.dev/config/
export default defineConfig(({ mode }) => ({
  plugins: [react(), devApi(mode)],
  server:{
    host:"0.0.0.0",
    port:3000,
  },
  build: {
    rollupOptions: {
      // Pages: the portfolio, the free tools hub and the QR code generator.
      input: {
        main: 'index.html',
        services: 'services/index.html',
        qr: 'qr-code-generator/index.html',
        resizer: 'image-resizer/index.html',
        imageToPdf: 'image-to-pdf/index.html',
        pdfToImage: 'pdf-to-image/index.html',
        // SEO landing pages (one per tool feature), generated by scripts/gen-pages.mjs.
        ...Object.fromEntries(landings.map((p) => [p.slug, `${p.slug}/index.html`])),
      },
    },
  },
}))
